from fastapi import Depends, FastAPI, Query
from fastapi.middleware.cors import CORSMiddleware
from sqlalchemy import select
from sqlalchemy.orm import Session

from .database import Base, engine, get_db
from .models import SensorReading
from .schemas import SensorReadingCreate, SensorReadingResponse


app = FastAPI(
    title="CowNect Backend API",
    version="0.1.0",
)


app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "https://cownect-app-dashboard.onrender.com",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


Base.metadata.create_all(bind=engine)

#message used to check if API is healthy
@app.get("/health")
def health():
    return {"status": "healthy"}


#receives a JSON from the Jetson and saves it to the database
@app.post(
    "/api/v1/readings",
    response_model=SensorReadingResponse,
    status_code=201,
)
def create_reading(
    reading: SensorReadingCreate,
    db: Session = Depends(get_db),
):
    #converts the reading into a row in the database
    database_reading = SensorReading(**reading.model_dump())

    #adds the row to the database session
    db.add(database_reading)

    #saves row in PostgreSQL
    db.commit()

    #refreshes row to get any values generated by PostgreSQL like row #
    db.refresh(database_reading)

    #returns row saved
    return database_reading


# Returns readings, optionally filtered by collar.
@app.get(
    "/api/v1/readings",
    response_model=list[SensorReadingResponse],
)
def get_readings(
    collar_id: str | None = None,
    limit: int = Query(default=100, ge=1, le=1000),
    db: Session = Depends(get_db),
):
    query = select(SensorReading)

    # If a collar is specified, only return that collar's readings.
    if collar_id is not None:
        query = query.where(SensorReading.collar_id == collar_id)

    query = (
        query
        .order_by(SensorReading.recorded_at.desc())
        .limit(limit)
    )

    return db.scalars(query).all()